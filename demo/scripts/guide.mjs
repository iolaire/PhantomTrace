// Writes NARRATION.md from scenes.json, so the guide never drifts from the real text.
//   npm run guide
import {writeFileSync} from 'node:fs';
import path from 'node:path';
import {config, root, wordCount} from './lib.mjs';

const WORDS_PER_SECOND = 2.6; // a calm read-aloud pace

const rows = config.scenes.map((scene, index) => {
  const words = wordCount(scene.narration);
  const readSec = words / WORDS_PER_SECOND;
  return {scene, index, words, readSec};
});
const totalWords = rows.reduce((sum, row) => sum + row.words, 0);
const totalTarget = rows.reduce((sum, row) => sum + row.scene.targetSec, 0);

const lines = [];
lines.push('# Narration Guide');
lines.push('');
lines.push('<!-- Generated by `npm run guide` from scenes.json. Edit the text in scenes.json, then run it again. -->');
lines.push('');
lines.push(
  `${config.scenes.length} scenes, ${totalWords} words, about ${Math.round(totalWords / WORDS_PER_SECOND)} s of speech, ` +
    `${totalTarget} s planned on screen. The contest limit is 180 s; this project warns above ${config.maxTotalSeconds} s.`,
);
lines.push('');
lines.push('## How to change the words and record your own voice');
lines.push('');
lines.push('1. Edit `narration` for a scene in `demo/scenes.json`. Spell hard words the way they sound ("I D" for ID).');
lines.push('2. Record that scene alone, 44.1 or 48 kHz, one take per file. Keep a half second of quiet at each end.');
lines.push('3. Save it as `demo/public/audio/<scene-id>.wav` (`.mp3`, `.m4a` and `.aac` also work). Use the id in the table below.');
lines.push('   Your file replaces the machine voice for that scene. Delete your file to go back to the placeholder.');
lines.push('4. Run `npm run sync` (the studio and render scripts do this for you). The scene length follows your recording.');
lines.push('5. `npm run studio` to preview. `npm run render` for the full video, or `npm run render:scene -- s04-reveal out/s04.mp4` for one scene.');
lines.push('');
lines.push('Machine-voice stand-ins: `npm run vo:placeholder` (uses the macOS `say` command, voice and speed set by');
lines.push('`PHANTOMTRACE_VO_VOICE` and `PHANTOMTRACE_VO_RATE`). Add `-- --all` to redo every scene after editing text.');
lines.push('The stand-in voice is only for timing. Replace it with your own before you submit.');
lines.push('');
lines.push('## Pace and length');
lines.push('');
lines.push('- Plan on about 2.6 words per second. A scene with 26 words needs about 10 seconds.');
lines.push('- Each scene lasts as long as your recording plus 0.6 s, or its video clip if that is longer.');
lines.push('- If the total is too long, cut words first, then trim clips with `trimStartSec` in `scenes.json`.');
lines.push('');
lines.push('## Scenes');
lines.push('');
lines.push('| # | Scene id | Plan (s) | Words | Visual |');
lines.push('|---|---|---|---|---|');
for (const {scene, index, words} of rows) {
  const visual =
    scene.visual === 'still'
      ? `screenshot \`${scene.still}\``
      : scene.visual === 'clip'
        ? 'screen recording (clip)'
        : scene.visual === 'terminal'
          ? 'terminal replay'
          : 'title card';
  lines.push(`| ${index + 1} | \`${scene.id}\` | ${scene.targetSec} | ${words} | ${visual} |`);
}
lines.push('');
for (const {scene, index, words, readSec} of rows) {
  lines.push(`### ${index + 1}. ${scene.title} (\`${scene.id}\`)`);
  lines.push('');
  lines.push(`Voice file: \`demo/public/audio/${scene.id}.wav\` · Plan: ${scene.targetSec} s · ${words} words (about ${readSec.toFixed(0)} s read aloud)`);
  lines.push('');
  lines.push(`> ${scene.narration}`);
  lines.push('');
  lines.push(`Screen: ${scene.record}`);
  if (scene.visual === 'clip') {
    lines.push('');
    lines.push(`Record with: \`Scripts/demo/record-clip.sh ${scene.id} 12\` (saves \`demo/public/clips/${scene.id}.mp4\`).`);
  }
  if (scene.callouts.length > 0) {
    lines.push('');
    lines.push(`On-screen labels: ${scene.callouts.map((c) => `"${c.text}" at ${c.atSec} s`).join('; ')}`);
  }
  lines.push('');
}
lines.push('## Honest-claims check');
lines.push('');
lines.push('Say only what the video shows. The Kiro scene says hooks "check" things before commits, because the hook');
lines.push('output was not captured (see `docs/KiroUsage.md`). If you add a claim, add its proof to the repo first.');
lines.push('');

writeFileSync(path.join(root, 'NARRATION.md'), lines.join('\n'));
console.log('wrote demo/NARRATION.md');
